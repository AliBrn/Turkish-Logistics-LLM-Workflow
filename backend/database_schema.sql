CREATE TABLE IF NOT EXISTS gonderenler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    telefon VARCHAR(30) UNIQUE,
    gonderen_adi VARCHAR(150),
    firma_adi VARCHAR(150)
);

CREATE TABLE IF NOT EXISTS ham_mesajlar (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    harici_mesaj_id VARCHAR(120) UNIQUE,
    gonderen_id BIGINT REFERENCES gonderenler(id),
    chat_id VARCHAR(120),
    chat_adi VARCHAR(200),
    mesaj_metni TEXT NOT NULL,
    mesaj_tarihi TIMESTAMP,
    islem_durumu VARCHAR(30) NOT NULL DEFAULT 'bekliyor'
);

CREATE TABLE IF NOT EXISTS cozumleme_kayitlari (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ham_mesaj_id BIGINT NOT NULL REFERENCES ham_mesajlar(id) ON DELETE CASCADE,
    ham_model_cevabi TEXT,
    duzeltilmis_json JSONB,
    basarili_mi BOOLEAN NOT NULL DEFAULT false,
    hata_mesaji TEXT
);

CREATE TABLE IF NOT EXISTS siparisler (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ham_mesaj_id BIGINT NOT NULL REFERENCES ham_mesajlar(id) ON DELETE CASCADE,
    cozumleme_id BIGINT REFERENCES cozumleme_kayitlari(id) ON DELETE SET NULL,
    siparis_no INTEGER NOT NULL,
    nereden VARCHAR(200),
    nereye VARCHAR(200),
    yuk_tipi VARCHAR(50),
    arac_tipi VARCHAR(80),
    kasa_tipi VARCHAR(120),
    durum VARCHAR(40) NOT NULL DEFAULT 'inceleniyor',
    operasyon_durumu VARCHAR(40) NOT NULL DEFAULT 'yeni',
    manuel_duzenlendi_mi BOOLEAN NOT NULL DEFAULT false
);

CREATE TABLE IF NOT EXISTS siparis_durum_gecmisi (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    siparis_id BIGINT NOT NULL REFERENCES siparisler(id) ON DELETE CASCADE,
    eski_durum VARCHAR(40),
    yeni_durum VARCHAR(40) NOT NULL,
    not_metni TEXT,
    degisim_tarihi TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS dogrulama_sorunlari (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ham_mesaj_id BIGINT REFERENCES ham_mesajlar(id) ON DELETE CASCADE,
    siparis_id BIGINT REFERENCES siparisler(id) ON DELETE CASCADE,
    cozumleme_id BIGINT REFERENCES cozumleme_kayitlari(id) ON DELETE SET NULL,
    sorun_tipi VARCHAR(80) NOT NULL,
    alan_adi VARCHAR(80),
    mevcut_deger TEXT,
    onerilen_deger TEXT,
    durum VARCHAR(30) NOT NULL DEFAULT 'acik',
    not_metni TEXT
);

CREATE TABLE IF NOT EXISTS json_import_state (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    source_name VARCHAR(120) UNIQUE NOT NULL,
    last_imported_index INTEGER NOT NULL DEFAULT -1,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_ham_mesajlar_islem_durumu ON ham_mesajlar(islem_durumu);
CREATE INDEX IF NOT EXISTS idx_ham_mesajlar_gonderen_id ON ham_mesajlar(gonderen_id);
CREATE INDEX IF NOT EXISTS idx_cozumleme_ham_mesaj_id ON cozumleme_kayitlari(ham_mesaj_id);
CREATE INDEX IF NOT EXISTS idx_siparisler_ham_mesaj_id ON siparisler(ham_mesaj_id);
CREATE INDEX IF NOT EXISTS idx_siparisler_durum ON siparisler(durum);
CREATE INDEX IF NOT EXISTS idx_siparisler_operasyon_durumu ON siparisler(operasyon_durumu);
CREATE INDEX IF NOT EXISTS idx_dogrulama_durum ON dogrulama_sorunlari(durum);
